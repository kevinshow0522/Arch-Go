import {writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {delimiter} from 'node:path';
import {readWorkbenchTemplate} from './workbench-template.mjs';
const require=createRequire(import.meta.url);
const {build}=require('esbuild');
const root=fileURLToPath(new URL('../',import.meta.url));
const {readMethodCatalog}=await import('./method-catalog.mjs');
const catalog=readMethodCatalog().framework;
const runtime=await build({entryPoints:[root+'web/project-workbench.mjs'],bundle:true,write:false,format:'iife',globalName:'KiGAGAProjectRuntime',platform:'browser',target:'es2022',minify:true});
const runtimeScript=runtime.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const methodJson=JSON.stringify(catalog).replace(/</g,'\\u003c');
const bundle=await build({entryPoints:[root+'web/workbench-v04-host.mjs'],bundle:true,write:false,format:'esm',platform:'browser',target:'es2022',minify:true,nodePaths:process.env.NODE_PATH?.split(delimiter).filter(Boolean)??[]});
const js=bundle.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const source=readWorkbenchTemplate(root);
if(!/\b(?:window|W)\.KiGAGAWorkbench\s*=/.test(source))throw new Error('Missing workbench interface');
const html=source.replace('</head>',()=>'<script>window.KIGAGA_EMBED={waitForData:true};window.KIGAGA_METHOD_CATALOG='+methodJson+';'+runtimeScript+'</script>\n</head>').replace('</body>',()=>'<script type="module">'+js+'</script>\n</body>');
mkdirSync(root+'assets',{recursive:true});
writeFileSync(root+'assets/workbench.html',html);
console.log('Built assets/workbench.html (UI v0.6, method '+catalog.method_version+', read-only host bridge)');
